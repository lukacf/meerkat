import { forgeBuildOptions } from "./build-config.mjs";
import { build } from "esbuild";
import { copyFile, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL(".", import.meta.url));
const rendererHash = createHash("sha256")
  .update(await readFile(new URL("freeform-animation.mjs", import.meta.url)))
  .digest("hex");
await writeFile(new URL("animation-review-renderer-hash.mjs", import.meta.url),
  `// Generated by build.mjs from the renderer bytes in this build.\nexport const ANIMATION_RENDERER_HASH='${rendererHash}';\n`);
await rm(new URL("dist/styles.css", import.meta.url), { force: true });
// Font file names carry a content hash; drop earlier builds' fonts.
await rm(new URL("dist/fonts/", import.meta.url), { recursive: true, force: true });
await mkdir(new URL("dist/", import.meta.url), { recursive: true });
await build(forgeBuildOptions());
await copyFile(
  new URL("index.html", import.meta.url),
  new URL("dist/index.html", import.meta.url),
);
await mkdir(new URL("dist/assets/", import.meta.url), { recursive: true });
await copyFile(
  new URL("../assets/meerkat-transparent.png", import.meta.url),
  new URL("dist/assets/meerkat-transparent.png", import.meta.url),
);
console.log(`Built Meta Forge at ${root}dist/`);
