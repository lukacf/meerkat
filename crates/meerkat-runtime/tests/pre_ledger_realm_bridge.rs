//! Release-boundary corpus: realms written by published pre-0.8.10 `rkat`
//! binaries must survive the explicit offline storage bridge.
//!
//! The 0.8.23 report was a user who followed the product's own remedy into a
//! dead end. A normal run told them to run
//! `storage migrate --apply --bridge-pre-0-8-10`; the bridge then refused
//! their realm because the oldest catalog it recognized was younger than the
//! realms it was named for. Nothing in the tree exercised the bridge against
//! bytes a released 0.7.x binary actually wrote, so the gap shipped.
//!
//! Everything here runs against `tests/fixtures/v0_7_x_pre_ledger_realm`,
//! minted by `mint_pre_ledger_fixture.py` from the published release assets.
//! It never constructs a legacy schema from current source: a hand-built
//! shape would only prove that this file and `sqlite.rs` agree with each
//! other.
//!
//! Each release contributes one or more *captures*. `bootstrap-only` is a run
//! with no credentials, which dies before admitting anything and leaves schema
//! plus a single `runtime_states` row. `attempted-turn` is a run with a dummy
//! provider key and an explicit model, which admits the operator input,
//! persists it, and dies at the provider call. Only the second kind carries
//! `runtime_input_states` rows, and only the second kind can therefore reach
//! the bridge's row-preparation callback. A corpus made solely of the first
//! kind can pass every assertion below while never executing the code that
//! decides whether a real operator's realm opens.

#![cfg(feature = "sqlite-store")]
#![allow(clippy::expect_used, clippy::panic, clippy::unwrap_used)]

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

use serde::Deserialize;

#[derive(Debug, Deserialize)]
struct PreLedgerFixtureManifest {
    schema_version: u32,
    fixture_id: String,
    data_classification: String,
    realm_id: String,
    releases: Vec<PreLedgerRelease>,
}

#[derive(Debug, Deserialize)]
struct PreLedgerRelease {
    meerkat_version: String,
    source_release: String,
    release_asset: String,
    release_asset_sha256: String,
    binary_version_output: String,
    binary_sha256: String,
    current_source_build: bool,
    captures: Vec<PreLedgerCapture>,
}

#[derive(Debug, Deserialize)]
struct PreLedgerCapture {
    capture_id: String,
    root: String,
    payloads: Vec<PreLedgerPayload>,
    sessions_sqlite_catalog: Vec<PreLedgerCatalogEntry>,
    sessions_sqlite_row_counts: BTreeMap<String, i64>,
    workgraph_sqlite_row_counts: BTreeMap<String, i64>,
    runtime_input_state_rows: Vec<PreLedgerInputRow>,
    carries_runtime_input_rows: bool,
}

#[derive(Debug, Deserialize)]
struct PreLedgerPayload {
    path: String,
    bytes: u64,
    sha256: String,
}

#[derive(Debug, Deserialize, PartialEq, Eq, PartialOrd, Ord, Clone)]
struct PreLedgerCatalogEntry {
    #[serde(rename = "type")]
    kind: String,
    name: String,
    sql: String,
}

/// One durable runtime input row, described by identity rather than by count.
/// A count alone would let a corpus claim to be row-bearing while carrying
/// something the callback never sees.
#[derive(Debug, Deserialize, PartialEq, Eq, Clone)]
struct PreLedgerInputRow {
    runtime_id: String,
    input_id: String,
    stored_input_state_version: u64,
    current_state: String,
    input_type: String,
    state_json_sha256: String,
}

/// Exactly the runtime tables the whole 0.7.x line created. If this list ever
/// needs editing to make a test pass, the fixture changed, not the contract.
const PRE_LEDGER_RUNTIME_TABLES: &[&str] = &[
    "runtime_auth_oauth_flow_state",
    "runtime_boundary_receipts",
    "runtime_input_states",
    "runtime_ops_lifecycle",
    "runtime_projection_quarantine",
    "runtime_session_snapshots",
    "runtime_states",
];

fn corpus_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/v0_7_x_pre_ledger_realm/corpus")
}

fn sha256_bytes(bytes: &[u8]) -> String {
    use sha2::{Digest as _, Sha256};
    let mut hasher = Sha256::new();
    hasher.update(bytes);
    format!("{:x}", hasher.finalize())
}

fn sha256_file(path: &Path) -> String {
    let bytes = std::fs::read(path)
        .unwrap_or_else(|error| panic!("read {} for hashing: {error}", path.display()));
    sha256_bytes(&bytes)
}

fn load_manifest() -> PreLedgerFixtureManifest {
    let path = corpus_root().join("fixture-manifest.json");
    let bytes = std::fs::read(&path).unwrap_or_else(|error| {
        panic!(
            "RELEASE BLOCKER: pre-ledger 0.7.x realm corpus is absent or unreadable at {}: \
             {error}; re-mint it with \
             tests/fixtures/v0_7_x_pre_ledger_realm/mint_pre_ledger_fixture.py using published \
             release assets, never current-source generated bytes",
            path.display()
        )
    });
    serde_json::from_slice(&bytes)
        .unwrap_or_else(|error| panic!("pre-ledger fixture manifest is invalid: {error}"))
}

fn capture_root(capture: &PreLedgerCapture) -> PathBuf {
    corpus_root().join(&capture.root)
}

/// Every file under `root`, as `/`-joined paths relative to it.
fn relative_files(root: &Path) -> BTreeSet<String> {
    fn walk(base: &Path, current: &Path, found: &mut BTreeSet<String>) {
        let entries = std::fs::read_dir(current)
            .unwrap_or_else(|error| panic!("read {}: {error}", current.display()));
        for entry in entries {
            let entry = entry
                .unwrap_or_else(|error| panic!("read entry in {}: {error}", current.display()));
            let path = entry.path();
            if path.is_dir() {
                walk(base, &path, found);
            } else {
                let relative = path.strip_prefix(base).unwrap_or_else(|error| {
                    panic!(
                        "{} is not under {}: {error}",
                        path.display(),
                        base.display()
                    )
                });
                found.insert(
                    relative
                        .components()
                        .map(|component| component.as_os_str().to_string_lossy().into_owned())
                        .collect::<Vec<_>>()
                        .join("/"),
                );
            }
        }
    }
    let mut found = BTreeSet::new();
    walk(root, root, &mut found);
    found
}

/// Copy a committed database out of the corpus before opening it. Opening it
/// in place would let SQLite create sidecars beside bytes that must stay
/// exactly as the published writer left them.
fn with_corpus_database<T>(
    source: &Path,
    profile: meerkat_sqlite::ConnectionProfile,
    body: impl FnOnce(&mut rusqlite::Connection) -> T,
) -> T {
    let scratch = tempfile::tempdir().expect("tempdir");
    let database = scratch.path().join(
        source
            .file_name()
            .unwrap_or_else(|| panic!("{} has no file name", source.display())),
    );
    std::fs::copy(source, &database)
        .unwrap_or_else(|error| panic!("copy {}: {error}", source.display()));
    let mut conn = meerkat_sqlite::open(&database, profile)
        .unwrap_or_else(|error| panic!("open {}: {error}", database.display()));
    body(&mut conn)
}

fn read_row_counts(source: &Path) -> BTreeMap<String, i64> {
    with_corpus_database(
        source,
        meerkat_sqlite::ConnectionProfile::ReadOnly,
        |conn| {
            let tables = {
                let mut statement = conn
                    .prepare(
                        "SELECT name FROM sqlite_master WHERE type = 'table' \
                     AND name NOT LIKE 'sqlite_%' ORDER BY name",
                    )
                    .expect("prepare catalog query");
                statement
                    .query_map([], |row| row.get::<_, String>(0))
                    .expect("query catalog")
                    .collect::<Result<Vec<_>, _>>()
                    .expect("collect catalog")
            };
            let mut counts = BTreeMap::new();
            for table in tables {
                let count: i64 = conn
                    .query_row(&format!("SELECT COUNT(*) FROM \"{table}\""), [], |row| {
                        row.get(0)
                    })
                    .unwrap_or_else(|error| panic!("count {table}: {error}"));
                counts.insert(table, count);
            }
            counts
        },
    )
}

fn read_runtime_input_rows(source: &Path) -> Vec<PreLedgerInputRow> {
    with_corpus_database(
        source,
        meerkat_sqlite::ConnectionProfile::ReadOnly,
        |conn| {
            let mut statement = conn
                .prepare(
                    "SELECT runtime_id, input_id, state_json FROM runtime_input_states \
                 ORDER BY runtime_id, input_id",
                )
                .expect("prepare input-state query");
            statement
                .query_map([], |row| {
                    Ok((
                        row.get::<_, String>(0)?,
                        row.get::<_, String>(1)?,
                        row.get::<_, Vec<u8>>(2)?,
                    ))
                })
                .expect("query input states")
                .map(|row| {
                    let (runtime_id, input_id, state) = row.expect("read input-state row");
                    let decoded: serde_json::Value =
                        serde_json::from_slice(&state).expect("input state is JSON");
                    PreLedgerInputRow {
                        stored_input_state_version: decoded
                            .get("stored_input_state_version")
                            .and_then(serde_json::Value::as_u64)
                            .unwrap_or_else(|| panic!("{runtime_id}/{input_id} has no version")),
                        current_state: decoded
                            .get("current_state")
                            .and_then(serde_json::Value::as_str)
                            .unwrap_or_default()
                            .to_string(),
                        input_type: decoded
                            .get("persisted_input")
                            .and_then(|input| input.get("input_type"))
                            .and_then(serde_json::Value::as_str)
                            .unwrap_or_default()
                            .to_string(),
                        state_json_sha256: sha256_bytes(&state),
                        runtime_id,
                        input_id,
                    }
                })
                .collect::<Vec<_>>()
        },
    )
}

/// Every input row's full decoded JSON, keyed by `runtime_id/input_id`.
///
/// The descriptor type above is deliberately narrow because it is also the
/// manifest's schema. Preservation needs the whole record.
fn read_runtime_input_json(source: &Path) -> BTreeMap<String, serde_json::Value> {
    with_corpus_database(
        source,
        meerkat_sqlite::ConnectionProfile::ReadOnly,
        |conn| {
            let mut statement = conn
                .prepare(
                    "SELECT runtime_id, input_id, state_json FROM runtime_input_states \
                 ORDER BY runtime_id, input_id",
                )
                .expect("prepare input-state query");
            statement
                .query_map([], |row| {
                    Ok((
                        row.get::<_, String>(0)?,
                        row.get::<_, String>(1)?,
                        row.get::<_, Vec<u8>>(2)?,
                    ))
                })
                .expect("query input states")
                .map(|row| {
                    let (runtime_id, input_id, state) = row.expect("read input-state row");
                    (
                        format!("{runtime_id}/{input_id}"),
                        serde_json::from_slice(&state).expect("input state is JSON"),
                    )
                })
                .collect::<BTreeMap<_, _>>()
        },
    )
}

fn captures(manifest: &PreLedgerFixtureManifest) -> Vec<(&PreLedgerRelease, &PreLedgerCapture)> {
    manifest
        .releases
        .iter()
        .flat_map(|release| {
            release
                .captures
                .iter()
                .map(move |capture| (release, capture))
        })
        .collect()
}

/// Resolve one capture by name.
///
/// Tests that examine a single realm name the capture they mean. Taking
/// whichever capture happens to sort first would silently change a test's
/// subject the next time a capture is added, and the two shapes here answer
/// different questions: `bootstrap-only` bridges today, `attempted-turn` does
/// not.
fn capture_named<'a>(
    manifest: &'a PreLedgerFixtureManifest,
    capture_id: &str,
) -> (&'a PreLedgerRelease, &'a PreLedgerCapture) {
    captures(manifest)
        .into_iter()
        .find(|(_, capture)| capture.capture_id == capture_id)
        .unwrap_or_else(|| panic!("the corpus carries no `{capture_id}` capture"))
}

/// The corpus must stay bound to the published artifacts it came from, and
/// must stay non-empty. A corpus that quietly loses its realms would let every
/// assertion below pass over nothing.
#[test]
fn pre_ledger_corpus_is_bound_to_published_release_artifacts() {
    let manifest = load_manifest();
    assert_eq!(manifest.schema_version, 2);
    assert_eq!(manifest.fixture_id, "meerkat-0.7.x-pre-ledger-realms");
    assert_eq!(
        manifest.data_classification, "synthetic_non_production",
        "production-redacted data is forbidden in a release fixture"
    );
    assert_eq!(manifest.realm_id, "legacy-realm");
    assert!(
        manifest.releases.len() >= 2,
        "the corpus must span more than one published 0.7.x release, found {}",
        manifest.releases.len()
    );

    let mut versions = BTreeSet::new();
    for release in &manifest.releases {
        assert!(
            versions.insert(release.meerkat_version.clone()),
            "duplicate release {} in the corpus",
            release.meerkat_version
        );
        assert!(
            release.meerkat_version.starts_with("0.7."),
            "this corpus is the pre-0.8.0 line, found {}",
            release.meerkat_version
        );
        assert!(
            !release.current_source_build,
            "release {} must be a published artifact, not a current-source build",
            release.meerkat_version
        );
        assert_eq!(
            release.binary_version_output,
            format!("rkat {}", release.meerkat_version),
            "corpus was not written by the published CLI it claims"
        );
        assert_eq!(
            release.source_release,
            format!(
                "https://github.com/lukacf/meerkat/releases/tag/v{}",
                release.meerkat_version
            )
        );
        assert!(
            release
                .release_asset
                .starts_with(&format!("rkat-{}-", release.meerkat_version)),
            "release asset {} does not name version {}",
            release.release_asset,
            release.meerkat_version
        );
        for (label, digest) in [
            ("release asset", &release.release_asset_sha256),
            ("producer binary", &release.binary_sha256),
        ] {
            assert_eq!(
                digest.len(),
                64,
                "{label} SHA-256 for {} has the wrong length",
                release.meerkat_version
            );
            assert!(
                digest
                    .bytes()
                    .all(|byte| byte.is_ascii_hexdigit() && !byte.is_ascii_uppercase()),
                "{label} SHA-256 for {} is not lowercase hexadecimal",
                release.meerkat_version
            );
        }

        assert!(
            !release.captures.is_empty(),
            "release {} binds no captures",
            release.meerkat_version
        );
        let mut capture_ids = BTreeSet::new();
        for capture in &release.captures {
            assert!(
                capture_ids.insert(capture.capture_id.clone()),
                "duplicate capture {} for release {}",
                capture.capture_id,
                release.meerkat_version
            );
            assert_eq!(
                capture.root,
                format!("realms/{}/{}", release.meerkat_version, capture.capture_id),
                "capture root does not name its own release and capture"
            );

            let realm = capture_root(capture);
            let mut declared = BTreeSet::new();
            for payload in &capture.payloads {
                let path = realm.join(&payload.path);
                assert_eq!(
                    sha256_file(&path),
                    payload.sha256,
                    "committed bytes of {} differ from their manifest digest",
                    path.display()
                );
                assert_eq!(
                    std::fs::metadata(&path)
                        .unwrap_or_else(|error| panic!("stat {}: {error}", path.display()))
                        .len(),
                    payload.bytes,
                    "committed size of {} differs from its manifest entry",
                    path.display()
                );
                declared.insert(payload.path.clone());
            }
            assert_eq!(
                relative_files(&realm),
                declared,
                "capture {} of release {} carries files the manifest does not bind (a WAL/SHM \
                 sidecar means the corpus was opened in place)",
                capture.capture_id,
                release.meerkat_version
            );
        }
    }
}

/// The corpus reproduces the shape the 0.8.23 report hit: seven runtime tables
/// and no ledger at all. This is the fact the bridge got wrong, so it is
/// asserted directly rather than inferred from a passing migration.
#[test]
fn pre_ledger_corpus_carries_the_unledgered_seven_table_runtime_shape() {
    let manifest = load_manifest();
    for (release, capture) in captures(&manifest) {
        let label = format!("{}/{}", release.meerkat_version, capture.capture_id);
        let catalog = &capture.sessions_sqlite_catalog;
        assert!(
            !catalog
                .iter()
                .any(|entry| entry.name.eq_ignore_ascii_case("meerkat_schema")),
            "capture {label} must have no migration ledger; that is what makes it unledgered"
        );
        let runtime_tables = catalog
            .iter()
            .filter(|entry| entry.kind == "table" && entry.name.starts_with("runtime_"))
            .map(|entry| entry.name.as_str())
            .collect::<BTreeSet<_>>();
        assert_eq!(
            runtime_tables,
            PRE_LEDGER_RUNTIME_TABLES.iter().copied().collect(),
            "capture {label} does not carry the 0.7.x runtime catalog"
        );
        // The two tables the bridge's youngest recognized catalog demanded.
        // Their absence is precisely why the released bridge refused.
        for absent in [
            "runtime_retired_ops_epochs",
            "runtime_compaction_projection_outbox",
            "runtime_mob_host_bindings",
            "runtime_mob_host_revocations",
        ] {
            assert!(
                !runtime_tables.contains(absent),
                "capture {label} unexpectedly has {absent}"
            );
        }
    }
}

/// The runtime catalog is byte-stable across the published 0.7.x span and
/// across capture profiles, so one frozen predecessor covers all of them, and
/// so a row-bearing realm cannot be dismissed as "a different schema". Proven
/// by comparison, not asserted in a comment.
#[test]
fn pre_ledger_runtime_catalog_is_identical_across_the_published_span() {
    let manifest = load_manifest();
    let runtime_catalog = |capture: &PreLedgerCapture| {
        let mut rows = capture
            .sessions_sqlite_catalog
            .iter()
            .filter(|entry| entry.name.starts_with("runtime_"))
            .cloned()
            .collect::<Vec<_>>();
        rows.sort();
        rows
    };
    let all = captures(&manifest);
    let ((first_release, first_capture), rest) =
        all.split_first().expect("corpus has at least one capture");
    let baseline = runtime_catalog(first_capture);
    assert!(
        !baseline.is_empty(),
        "baseline runtime catalog for {}/{} is empty",
        first_release.meerkat_version,
        first_capture.capture_id
    );
    for (release, capture) in rest {
        assert_eq!(
            runtime_catalog(capture),
            baseline,
            "runtime catalog drifted between {}/{} and {}/{}",
            first_release.meerkat_version,
            first_capture.capture_id,
            release.meerkat_version,
            capture.capture_id
        );
    }
}

/// Row counts are read out of the committed databases, not believed from the
/// manifest. A manifest that claims rows the file does not have would rebuild
/// the exact failure this corpus exists to prevent: evidence that answers a
/// different question than the one asked.
#[test]
fn pre_ledger_corpus_row_counts_are_read_from_the_committed_bytes() {
    let manifest = load_manifest();
    for (release, capture) in captures(&manifest) {
        let label = format!("{}/{}", release.meerkat_version, capture.capture_id);
        let realm = capture_root(capture);

        let sessions = read_row_counts(&realm.join("sessions.sqlite3"));
        assert_eq!(
            sessions, capture.sessions_sqlite_row_counts,
            "capture {label} sessions.sqlite3 row counts differ from the manifest"
        );
        let workgraph = read_row_counts(&realm.join("workgraph.sqlite3"));
        assert_eq!(
            workgraph, capture.workgraph_sqlite_row_counts,
            "capture {label} workgraph.sqlite3 row counts differ from the manifest"
        );

        let input_rows = read_runtime_input_rows(&realm.join("sessions.sqlite3"));
        assert_eq!(
            input_rows, capture.runtime_input_state_rows,
            "capture {label} runtime input rows differ from the manifest"
        );
        assert_eq!(
            input_rows.len() as i64,
            *sessions.get("runtime_input_states").unwrap_or(&0),
            "capture {label} input-row descriptors disagree with its own row count"
        );
        assert_eq!(
            capture.carries_runtime_input_rows,
            !input_rows.is_empty(),
            "capture {label} misdeclares whether it carries runtime input rows"
        );
    }
}

/// At least one capture must be able to reach
/// `prepare_pre_0_8_10_runtime_input_states`. Round one's corpus could not:
/// every realm in it was written by a run that died before admitting any
/// input, so the callback that decides whether a real operator's realm opens
/// was never executed by any test, and a defect inside it shipped unseen.
#[test]
fn pre_ledger_corpus_can_reach_the_runtime_input_preparation_path() {
    let manifest = load_manifest();
    let row_bearing = captures(&manifest)
        .into_iter()
        .filter(|(_, capture)| capture.carries_runtime_input_rows)
        .collect::<Vec<_>>();
    assert!(
        row_bearing.len() >= 2,
        "the corpus must carry realms with durable runtime input rows from more than one \
         published vintage; found {} such capture(s). Without them the bridge's row-preparation \
         callback is never executed and this file proves only that empty realms migrate.",
        row_bearing.len()
    );
    for (release, capture) in row_bearing {
        let rows = read_runtime_input_rows(&capture_root(capture).join("sessions.sqlite3"));
        assert!(
            !rows.is_empty(),
            "capture {}/{} claims runtime input rows but the committed database has none",
            release.meerkat_version,
            capture.capture_id
        );
        for row in rows {
            assert_eq!(
                row.stored_input_state_version, 3,
                "the 0.7.x line wrote stored_input_state_version 3; {}/{} has {}",
                release.meerkat_version, capture.capture_id, row.stored_input_state_version
            );
        }
    }
}

/// The whole point: every realm in the corpus bridges to the current schema.
///
/// Before the 0.7.x predecessor was registered this failed with
/// `UnledgeredSchemaNoMatch { domain: "runtime-store", target_version: 3 }` -
/// the exact error the 0.8.23 report quoted.
#[test]
fn published_pre_ledger_realms_bridge_to_the_current_schema() {
    let manifest = load_manifest();
    assert!(!manifest.releases.is_empty(), "corpus has no realms to run");

    // Every capture is run before anything is reported. A test that dies on
    // the first refusal hides how far the damage reaches, and the operator
    // question here is exactly "which of my realms open".
    let mut refusals = Vec::new();
    for (release, capture) in captures(&manifest) {
        let label = format!("{}/{}", release.meerkat_version, capture.capture_id);
        if let Err(refusal) = bridge_one_capture(&label, &capture_root(capture)) {
            refusals.push(refusal);
        }
    }
    assert!(
        refusals.is_empty(),
        "the bridge named in the product's own remedy refused {} of the corpus realms:\n\n{}",
        refusals.len(),
        refusals.join("\n\n")
    );
}

/// Bridge one capture's `sessions.sqlite3` through all three domains, exactly
/// as `storage migrate --apply --bridge-pre-0-8-10` does. Returns the refusal
/// text, including what the ledger was left holding, rather than panicking.
fn bridge_one_capture(label: &str, realm: &Path) -> Result<(), String> {
    let source = realm.join("sessions.sqlite3");
    let scratch = tempfile::tempdir().expect("tempdir");
    let database = scratch.path().join("sessions.sqlite3");
    std::fs::copy(&source, &database)
        .unwrap_or_else(|error| panic!("copy {label} corpus: {error}"));

    let mut conn = meerkat_sqlite::open(
        &database,
        meerkat_sqlite::ConnectionProfile::Maintenance { write: true },
    )
    .unwrap_or_else(|error| panic!("open {label} corpus for maintenance: {error}"));

    let session_domain = &meerkat_store::sqlite_store::SESSION_STORE_DOMAIN;
    let runtime_domain = &meerkat_runtime::store::sqlite::RUNTIME_STORE_DOMAIN;
    let schedule_domain = &meerkat_store::schedule_sqlite_store::SCHEDULE_STORE_DOMAIN;

    let ledger_state = |conn: &rusqlite::Connection| {
        [session_domain, runtime_domain, schedule_domain]
            .iter()
            .map(|domain| {
                let stamped = meerkat_sqlite::domain_version(conn, domain.name)
                    .unwrap_or_else(|error| panic!("read {} ledger: {error}", domain.name));
                match stamped {
                    Some(version) => format!("{}=v{version}", domain.name),
                    None => format!("{}=unledgered", domain.name),
                }
            })
            .collect::<Vec<_>>()
            .join(", ")
    };

    let session = meerkat_sqlite::bridge_unledgered_domain(
        &mut conn,
        session_domain,
        session_domain.supported_version(),
        &[1],
        Some(meerkat_store::sqlite_store::prepare_pre_0_8_10_session_base_schema),
    )
    .map_err(|error| {
        format!(
            "{label}: session-store bridge refused: {error}\n  ledger after: {}",
            ledger_state(&conn)
        )
    })?;
    assert_eq!(session.from_version, 1, "{label} session source version");
    assert_eq!(
        session.to_version,
        session_domain.supported_version(),
        "{label} session target version"
    );

    let runtime = meerkat_sqlite::bridge_unledgered_domain(
        &mut conn,
        runtime_domain,
        runtime_domain.supported_version(),
        &[1],
        Some(meerkat_runtime::store::sqlite::prepare_pre_0_8_10_runtime_input_states),
    )
    .map_err(|error| {
        format!(
            "{label}: runtime-store bridge refused: {error}\n  ledger after: {}\n  \
             This is the 0.8.23 defect: the bridge named in the product's own remedy \
             cannot open the realm its target releases wrote.",
            ledger_state(&conn)
        )
    })?;
    assert_eq!(runtime.from_version, 1, "{label} runtime source version");
    assert_eq!(
        runtime.to_version,
        runtime_domain.supported_version(),
        "{label} runtime target version"
    );

    let schedule = meerkat_sqlite::bridge_unledgered_domain(
        &mut conn,
        schedule_domain,
        schedule_domain.supported_version(),
        &[1],
        None,
    )
    .map_err(|error| {
        format!(
            "{label}: schedule-store bridge refused: {error}\n  ledger after: {}",
            ledger_state(&conn)
        )
    })?;
    assert_eq!(schedule.from_version, 1, "{label} schedule source version");
    assert_eq!(
        schedule.to_version,
        schedule_domain.supported_version(),
        "{label} schedule target version"
    );

    // The ledger is the durable proof, not the in-memory report.
    for domain in [session_domain, runtime_domain, schedule_domain] {
        let stamped = meerkat_sqlite::domain_version(&conn, domain.name)
            .unwrap_or_else(|error| panic!("read {} ledger: {error}", domain.name))
            .unwrap_or_else(|| panic!("{} has no ledger row after bridging", domain.name));
        assert_eq!(
            stamped,
            domain.supported_version(),
            "{label} realm left {} at version {stamped}",
            domain.name
        );
    }

    // Re-running the bridge on a bridged realm is a verified no-op, so an
    // operator who repeats the documented command is not punished.
    for domain in [session_domain, runtime_domain, schedule_domain] {
        let repeat = meerkat_sqlite::bridge_unledgered_domain(
            &mut conn,
            domain,
            domain.supported_version(),
            &[1],
            None,
        )
        .unwrap_or_else(|error| {
            panic!(
                "re-running the {label} bridge for {} refused: {error}",
                domain.name
            )
        });
        assert_eq!(repeat.from_version, domain.supported_version());
        assert_eq!(repeat.to_version, domain.supported_version());
    }
    Ok(())
}

