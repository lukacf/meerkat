//! Pure inventory for the trusted application compiler before preparation.
//!
//! Native owns durable-identity lowering and the mob realm spelling. These
//! bindings describe the declared roster only: they do not establish sessions,
//! registration, destinations, tool surfaces, grants or original-source roles.

use super::{DurableAgentSpec, MobMemberBinding, read_regular_artifact};
use crate::application_bootstrap::{InstallerProgress, emit};
use meerkat_mobkit::member_comms_id::roster_member_id_for_identity;
use serde::{Deserialize, Serialize};
use std::{collections::BTreeSet, path::Path};

/// Generated by the application's existing compiler from its desired roster.
/// The helper is selected by exact durable identity, never by a runtime alias,
/// profile similarity or the native member string produced by this operation.
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ApplicationInventoryInput {
    pub schema: u32,
    pub mob_id: String,
    pub roster: Vec<DurableAgentSpec>,
    pub helper_identity: String,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ApplicationInventoryMember {
    pub identity: String,
    pub member: MobMemberBinding,
}

/// Same-order mapping for the declared roster. The trusted compiler still
/// selects each original route by its exact identity. Being a non-helper row
/// does not grant acquisition or make it an authenticated original source.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ApplicationInventory {
    pub schema: u32,
    pub mob_id: String,
    pub realm_id: String,
    pub helper_identity: String,
    pub members: Vec<ApplicationInventoryMember>,
}

impl ApplicationInventoryInput {
    /// No filesystem, runtime or native owner is opened by this operation.
    /// The roster and all its backend, binding and application fields remain
    /// with the caller unchanged; only identity/profile facts are projected.
    pub fn lower(&self) -> Result<ApplicationInventory, String> {
        if self.schema != 1 || self.roster.is_empty() {
            return Err("inventory requires schema 1 and a nonempty declared roster".into());
        }
        let realm_id = meerkat_core::mob_realm_id(&self.mob_id)
            .map_err(|error| error.to_string())?;
        let mut identities = BTreeSet::new();
        let mut members = BTreeSet::new();
        let mut helper_found = false;
        let mut inventory = Vec::with_capacity(self.roster.len());
        for row in &self.roster {
            let member = MobMemberBinding {
                mob_id: self.mob_id.clone(),
                role: row.profile.as_str().to_owned(),
                member: roster_member_id_for_identity(row.identity.as_str()).to_string(),
            };
            member.comms_name().map_err(|error| error.to_string())?;
            if !identities.insert(row.identity.as_str()) || !members.insert(member.member.clone()) {
                return Err("inventory repeats a durable identity or native member".into());
            }
            helper_found |= row.identity.as_str() == self.helper_identity;
            inventory.push(ApplicationInventoryMember {
                identity: row.identity.to_string(),
                member,
            });
        }
        if !helper_found {
            return Err("selected helper identity is absent from the declared roster".into());
        }
        Ok(ApplicationInventory {
            schema: 1,
            mob_id: self.mob_id.clone(),
            realm_id: realm_id.to_string(),
            helper_identity: self.helper_identity.clone(),
            members: inventory,
        })
    }
}

/// Existing installer dispatch invokes this before pipes or a runtime exist.
/// The compiler supplies its generated input; stdout is the only output.
pub(crate) fn command(args: &[String], progress: &mut InstallerProgress) -> Result<(), String> {
    let [_, input_flag, input_path] = args else {
        return Err("expected --lower-application-inventory --input FILE".into());
    };
    if input_flag != "--input" {
        return Err("invalid application inventory arguments".into());
    }
    progress.phase = "validation";
    let bytes = read_regular_artifact(Path::new(input_path))?;
    let input: ApplicationInventoryInput = serde_json::from_slice(&bytes)
        .map_err(|error| error.to_string())?;
    let inventory = input.lower()?;
    progress.phase = "receipt";
    emit(&inventory)
}

