"""Build plan/receipt controls with inert command interfaces, not compiler proof."""
from __future__ import annotations

import copy
import importlib.util
from pathlib import Path
import sys
import time
import unittest
from unittest.mock import patch

SPEC = importlib.util.spec_from_file_location("node_build_fixtures", Path(__file__).with_name("test_selected_node_install.py"))
N = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(N)
M = N.MODULE


def snapshot(root):
    return {str(p.relative_to(root)): p.read_bytes() for p in root.rglob("*") if p.is_file()}


class SelectedNodeBuildTests(unittest.TestCase):
    def setUp(self):
        self.f = N.SelectedNodeTests()
        self.f.setUp()
        self.addCleanup(self.f.doCleanups)
        self.f.software()
        self.runtime = str(Path(sys.executable).resolve())
        self.target = {"node_sha256": M.node_runtime_hash(self.runtime), "node_version": "v24.19.0",
                       "node_abi": "137", "platform": "linux", "arch": "x64",
                       "libc": {"family": "glibc", "version": "2.39"}}
        self.profile = {"schema_version": 1, "scope": "selected_node_build", "target": self.target,
            "executables": {"compile": {"path": self.runtime, "sha256": self.target["node_sha256"]}},
            "files": {}, "environment": {"PATH": "/usr/bin:/bin", "LANG": "C.UTF-8"},
            "limits": {"timeout_seconds": 900, "file_bytes": 1048576, "total_output_bytes": 2097152}}
        self.build = {"schema_version": 1, "target": self.target,
            "inputs": [{"source": {"npm": "node_modules/@outside/server/dist/main.js"}, "path": "source.js"}],
            "steps": [{"executable": "compile", "arguments": ["source.js", "out/addon.node", "literal ${HOME}; $(never-shell)"]}],
            "outputs": [{"path": "out/addon.node", "destination": "node_modules/@outside/server/build/addon.node", "replaces_sha256": None}]}
        self.generated = b"inert generated bytes; never imported"
        self.fail_build = False
        self.mutate_original = False
        self.bind()

    def bind(self):
        self.f.files[M.NODE_BUILD_PLAN] = M.encoded(self.build)
        self.f.bind()
        profile_path = self.f.root / "build-profile.json"
        profile_path.write_bytes(M.encoded(self.profile))
        self.f.args.node_build_profile = str(profile_path)
        self.f.args.node_build_profile_sha256 = M.sha(profile_path.read_bytes())
        (self.f.bundle / "plan.json").write_bytes(M.encoded(self.f.plan))
        review = M.review_node_build(self.closure(), self.f.args)
        (self.f.bundle / "build-review.json").write_bytes(M.encoded(review))
        return review

    def closure(self):
        return M.selected_npm_closure(self.f.files, self.f.plan)

    def fake_run(self, argv, cwd, env, label, timeout=900, *, discard_output=False):
        if label == "node-runtime":
            self.f.calls.append(label)
            return M.encoded([self.target["node_version"], self.target["platform"], self.target["arch"]])
        if label == "node-native-target":
            self.f.calls.append(label)
            return M.encoded({k: v for k, v in self.target.items() if k != "node_sha256"})
        if label.startswith("build-"):
            self.f.calls.append(label)
            self.assertTrue(discard_output)
            self.assertEqual(cwd, self.f.destination / "build-work")
            self.assertEqual(env, {**self.profile["environment"], "TMPDIR": str(cwd / "tmp")})
            self.assertEqual(argv, [self.runtime, *self.build["steps"][0]["arguments"]])
            self.assertGreater(timeout, 0)
            self.assertLessEqual(timeout, 900)
            if self.fail_build:
                raise M.InstallError("controlled failed compiler exit")
            if self.mutate_original:
                (self.f.destination / "node_modules/@outside/server/dist/main.js").write_bytes(b"mutated")
            for output in self.build["outputs"]:
                path = cwd / output["path"]
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(self.generated)
            return b""
        return self.f.fake_run(argv, cwd, env, label, timeout)

    def install(self):
        with patch.object(M, "run", side_effect=self.fake_run):
            return M.install_selected_node(self.f.args)

    def check(self):
        before = snapshot(self.f.destination)
        with patch.object(M, "readback_validator", return_value=M.encoded(self.f.plan)), patch.object(M, "run") as run:
            result = M.verify_existing_selected(self.f.args)
        run.assert_not_called()
        self.assertEqual(snapshot(self.f.destination), before)
        return result

    def test_host_executable_uses_runtime_bound_and_inputs_keep_file_bound(self):
        header = self.f.root / "small-header.h"
        header.write_bytes(b"header")
        self.profile["files"]["header"] = {"path": str(header), "sha256": M.sha(header.read_bytes())}
        self.profile["limits"]["file_bytes"] = 8
        self.bind()
        self.assertGreater(Path(self.runtime).stat().st_size, 8)
        # Use a small file limit to exercise the actual bounded reads without
        # allocating a 64 MiB fixture. Executable and aggregate bounds stay real.
        with patch.object(M, "MAX_FILE", 8):
            observed = M.node_build_profile(self.f.args)
            self.assertEqual(observed["payloads"]["executables"]["compile"], Path(self.runtime).read_bytes())
            self.assertEqual(observed["payloads"]["files"]["header"], b"header")
            header.write_bytes(b"too large")
            self.profile["files"]["header"]["sha256"] = M.sha(header.read_bytes())
            raw = M.encoded(self.profile)
            Path(self.f.args.node_build_profile).write_bytes(raw)
            self.f.args.node_build_profile_sha256 = M.sha(raw)
            with self.assertRaises(M.InstallError):
                M.node_build_profile(self.f.args)

    def test_literal_review_addition_original_bytes_and_inert_readback(self):
        original = snapshot(self.f.bundle)
        review = self.bind()
        self.assertEqual(review["commands"][0]["argv"][-1], "literal ${HOME}; $(never-shell)")
        receipt = self.install()
        self.assertEqual(snapshot(self.f.bundle), original)
        self.assertEqual(receipt["node_build"]["review"], review)
        self.assertEqual(receipt["node_build"]["steps"], [{"index": 0, "exit_code": 0}])
        self.assertEqual(self.check()["retained_payloads"]["node_build"], receipt["node_build"])
        self.assertEqual(self.f.calls.count("npm-install"), 1)
        self.assertEqual(self.f.calls.count("build-0"), 1)
        self.assertFalse((self.f.destination / "lifecycle-script-ran").exists())

    def test_generated_javascript_entrypoint_requires_exact_output_membership(self):
        self.f.plan["entrypoint"]["executable"] = "dist/generated.js"
        with self.assertRaises(M.InstallError):
            self.closure()
        self.build["outputs"][0].update(path="out/generated.js", destination="node_modules/@outside/server/dist/generated.js")
        self.bind()
        receipt = self.install()
        self.assertTrue(receipt["command"][1].endswith("/dist/generated.js"))
        self.check()
        files = {k: v for k, v in self.f.files.items() if k != M.NODE_BUILD_PLAN}
        with self.assertRaises(M.InstallError):
            M.selected_npm_closure(files, self.f.plan)

    def test_explicit_replacement_requires_original_hash_and_preserves_archive(self):
        original = self.closure()["build"]["originals"]["node_modules/@outside/server/dist/main.js"]
        row = self.build["outputs"][0]
        row.update(destination="node_modules/@outside/server/dist/main.js", replaces_sha256="0" * 64)
        self.f.files[M.NODE_BUILD_PLAN] = M.encoded(self.build)
        with self.assertRaises(M.InstallError):
            self.closure()
        row["replaces_sha256"] = M.sha(original)
        self.bind()
        receipt = self.install()
        self.assertEqual(M.npm_archive(self.f.files["artifact.tgz"])["files"]["dist/main.js"], original)
        self.assertEqual(receipt["node_build"]["outputs"][row["destination"]]["sha256"], M.sha(self.generated))
        self.check()

    def test_plan_rejects_unknown_tool_missing_profile_target_and_path_alias(self):
        for mutation in (
            lambda: self.build["steps"][0].update(executable="not-host-selected"),
            lambda: self.build["target"].update(node_abi="138"),
            lambda: self.build["outputs"][0].update(destination="node_modules/@outside/server/DIST/main.js"),
            lambda: self.build["outputs"][0].update(path="../outside"),
            lambda: self.build["outputs"][0].update(destination="node_modules/unselected/output.node"),
            lambda: self.build["outputs"][0].update(path="source.js"),
        ):
            before = copy.deepcopy(self.build)
            # target is shared deliberately in the fixture; detach for mutation.
            self.build = copy.deepcopy(before)
            mutation()
            with self.assertRaises((M.InstallError, OSError)):
                self.bind()
            self.build = before
        self.bind()
        self.f.args.node_build_profile = None
        with self.assertRaises(M.InstallError):
            M.review_node_build(self.closure(), self.f.args)

    def test_failed_command_or_changed_original_never_publishes_ready(self):
        self.fail_build = True
        with self.assertRaises(M.InstallError):
            self.install()
        self.assertFalse((self.f.destination / "ready").exists())
        self.assertTrue((self.f.destination / "inputs/artifact.tgz").exists())
        self.f.destination = self.f.root / "second-consumer"
        self.fail_build, self.mutate_original = False, True
        self.bind()
        with self.assertRaises(M.InstallError):
            self.install()
        self.assertFalse((self.f.destination / "ready").exists())

    def test_output_tamper_extra_file_symlink_and_tool_change_refuse_readback(self):
        self.install()
        output = self.f.destination / self.build["outputs"][0]["destination"]
        output.write_bytes(b"changed")
        with self.assertRaises(M.InstallError):
            self.check()
        output.write_bytes(self.generated)
        extra = output.with_name("unselected.node")
        extra.write_bytes(b"extra")
        with self.assertRaises(M.InstallError):
            self.check()
        extra.unlink()
        output.unlink()
        output.symlink_to(self.f.root / "absent")
        with self.assertRaises((M.InstallError, OSError)):
            self.check()
        output.unlink()
        output.write_bytes(self.generated)
        profile = Path(self.f.args.node_build_profile)
        profile.write_bytes(profile.read_bytes() + b" ")
        with self.assertRaises(M.InstallError):
            self.check()

    def test_planning_projection_has_ids_without_host_paths_or_environment_values(self):
        observed = M.describe_node_build(self.f.args)
        self.assertEqual(observed["executables"]["compile"]["sha256"], self.target["node_sha256"])
        self.assertEqual(observed["environment_keys"], ["LANG", "PATH"])
        self.assertNotIn(self.runtime, M.encoded(observed).decode())
        self.assertNotIn("/usr/bin:/bin", M.encoded(observed).decode())

    def test_reserved_plan_does_not_change_prebuilt_acquisition_receipt(self):
        spec = importlib.util.spec_from_file_location("build_prebuilt_fixture", Path(__file__).with_name("test_selected_node_prebuilt.py"))
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        case = module.SelectedNodePrebuiltTests()
        case.setUp()
        self.addCleanup(case.doCleanups)
        original = case.f.files[M.NODE_NATIVE_SOURCE]
        build = copy.deepcopy(self.build)
        build["target"] = case.target
        case.f.files[M.NODE_BUILD_PLAN] = M.encoded(build)
        case.f.bind()
        closure = M.selected_npm_closure(case.f.files, case.f.plan)
        self.assertEqual(case.f.files[M.NODE_NATIVE_SOURCE], original)
        self.assertEqual(closure["native"]["summary"]["source_receipt_sha256"], M.sha(original))
        self.assertIn("build", closure)


if __name__ == "__main__":
    unittest.main()
