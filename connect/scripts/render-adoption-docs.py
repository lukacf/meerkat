#!/usr/bin/env python3
"""Project the canonical OSS inventory into its public Mintlify page.

This reads planning metadata only. It does not import, install or execute any
integration, and it does not change an inventory entry's implementation state.
"""

from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import html
import json
from pathlib import Path
import sys
from urllib.parse import urlparse


ROOT = Path(__file__).resolve().parents[1]
INVENTORY = ROOT / "docs" / "adoption" / "oss-inventory.json"
OUTPUT = ROOT / "docs" / "site" / "library" / "candidates.mdx"
ROUTE_NAMES = {
    "maintained-mcp": "Maintained MCP server",
    "agno-toolkit-adapter": "Agno toolkit adapter",
    "activepieces-action-adapter": "Activepieces action adapter",
}
STATES = {"candidate", "runnable", "adopted"}


def display(value: object) -> str:
    """Escape inventory strings as one line of Markdown/MDX table text."""
    text = " ".join(str(value).split())
    text = text.replace("\u2013", "-").replace("\u2014", "-")
    text = html.escape(text, quote=False)
    for source, replacement in (
        ("{", "&#123;"),
        ("}", "&#125;"),
        ("|", "&#124;"),
        ("[", "&#91;"),
        ("]", "&#93;"),
        ("`", "&#96;"),
        ("*", "&#42;"),
        ("_", "&#95;"),
    ):
        text = text.replace(source, replacement)
    return text


def source_link(source: dict) -> str:
    url = source["url"]
    parsed = urlparse(url)
    if parsed.scheme != "https" or not parsed.netloc or any(c in url for c in " \n\r\t()<>\"'"):
        raise ValueError(f"invalid public source URL: {url!r}")
    return f"[Source]({url})"


def validate(inventory: dict) -> None:
    if inventory["schema_version"] != 1:
        raise ValueError("expected inventory schema_version 1")
    if inventory["inventory_kind"] != "candidate_oss_integrations":
        raise ValueError("expected candidate_oss_integrations inventory")
    integrations = inventory["integrations"]
    batches = {batch["id"]: batch for batch in inventory["batches"]}
    snapshots = {snapshot["id"]: snapshot for snapshot in inventory["source_snapshots"]}
    for field in ("id", "canonical_service_group"):
        values = [row[field] for row in integrations]
        if len(values) != len(set(values)):
            raise ValueError(f"duplicate integration {field}; deduplicate the canonical inventory")
    for row in integrations:
        if row["status"] not in STATES:
            raise ValueError(f"unknown implementation state for {row['id']}")
        if row["batch"] not in batches:
            raise ValueError(f"unknown batch for {row['id']}")
        if row["adoption_route"] not in ROUTE_NAMES:
            raise ValueError(f"unknown adoption route for {row['id']}")
        if not row["sources"]:
            raise ValueError(f"missing source for {row['id']}")
        for source in row["sources"]:
            snapshot = snapshots[source["source_snapshot"]]
            if source["revision"] != snapshot["revision"]:
                raise ValueError(f"source revision differs from snapshot for {row['id']}")
            source_link(source)
    counts = inventory["counts"]
    states = Counter(row["status"] for row in integrations)
    expected = {
        "distinct_integrations": len(integrations),
        "candidate": states["candidate"],
        "runnable": states["runnable"],
        "adopted": states["adopted"],
        "by_route": dict(Counter(row["adoption_route"] for row in integrations)),
        "by_batch": dict(Counter(row["batch"] for row in integrations)),
    }
    for key, value in expected.items():
        if counts[key] != value:
            raise ValueError(f"inventory count {key!r} disagrees with its rows")


def render(inventory: dict, digest: str) -> str:
    integrations = inventory["integrations"]
    states = Counter(row["status"] for row in integrations)
    routes = Counter(row["adoption_route"] for row in integrations)
    lines = [
        "---",
        'title: "OSS candidate inventory"',
        'description: "Source-backed upstream candidates and proposed reuse batches, with implementation states kept explicit."',
        'icon: "list-check"',
        "---",
        "",
        "{/* Generated by scripts/render-adoption-docs.py from docs/adoption/oss-inventory.json. Edit the inventory, not this list. */}",
        "",
        "This inventory identifies concrete upstream implementations for the [OSS adoption program](/library/adoption). It is a planning input, not the list of integrations already supported by Toolkit.",
        "",
        "| Inventory measure | Recorded count |",
        "| --- | --- |",
        f"| Distinct service/system identities | {len(integrations)} |",
        f"| Candidate | {states['candidate']} |",
        f"| Runnable | {states['runnable']} |",
        f"| Adopted | {states['adopted']} |",
        "",
        "The target remains **at least 100 adopted identities** with useful operations and supported host setup after documented authentication/configuration. Candidate source review does not establish installation, execution, license approval or account readiness. Versions, SDK languages and alternate upstream implementations do not multiply the distinct count.",
        "",
        "The public projection omits internal evidence records. The canonical inventory retains exact source hashes, prerequisites, auth observations, host coupling and unresolved questions. Its adopted count concerns these entries; it does not replace the requirements ledger or prove the complete product outcomes.",
        "",
        "## Proposed reuse routes",
        "",
        "| Route | Inventory entries | Development purpose |",
        "| --- | --- | --- |",
    ]
    purposes = {
        "maintained-mcp": "Compose the maintained implementation through the supported MCP owner and a documented setup path",
        "agno-toolkit-adapter": "Adapt actual toolkit functions and schemas with explicit host account/context inputs",
        "activepieces-action-adapter": "Adapt real service actions and their declared properties/authentication contract",
    }
    for route, name in ROUTE_NAMES.items():
        if routes[route]:
            lines.append(f"| {name} | {routes[route]} | {purposes[route]} |")
    lines += [
        "",
        "These routes are proposed engineering choices. They are not a resolver for user requests and do not imply that an adapter is already implemented. Prove shared adapters across deliberately different integrations, then retain per-entry execution and setup evidence as each batch advances.",
        "",
        "## Candidate batches",
        "",
        "Each source link points to the recorded upstream implementation at its pinned revision. A batch groups common adaptation work; its priority does not imply support or readiness.",
        "",
        "<AccordionGroup>",
    ]
    for batch in inventory["batches"]:
        entries = sorted((row for row in integrations if row["batch"] == batch["id"]), key=lambda row: (row["name"].casefold(), row["id"]))
        if not entries:
            continue
        title = html.escape(f"{batch['name']} ({len(entries)})", quote=True)
        title = title.replace("\u2013", "-").replace("\u2014", "-")
        lines += [
            f'  <Accordion title="{title}">',
            "",
            f"Route: **{ROUTE_NAMES[batch['adoption_route']]}**.",
            "",
            "| Integration | State | Pinned implementation |",
            "| --- | --- | --- |",
        ]
        for row in entries:
            links = " / ".join(dict.fromkeys(source_link(source) for source in row["sources"]))
            lines.append(f"| {display(row['name'])} | {display(row['status'])} | {links} |")
        lines += ["", "  </Accordion>"]
    lines += [
        "</AccordionGroup>",
        "",
        "## How this page stays current",
        "",
        f"Inventory observation: **{display(inventory['generated_at'])}**. This page is generated from `docs/adoption/oss-inventory.json`; no second service list is maintained by hand.",
        "",
        f"Source inventory SHA-256: `{digest}`.",
        "",
        "Candidate review should resolve dependencies, license/provenance, useful operation coverage, authentication and host coupling before advancing the entry. [Adoption criteria](/library/adoption) define the required evidence. [Agent-led acquisition](/concepts/acquisition) remains an equal product outcome and must work for integrations outside this starting inventory.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated public page is missing or stale")
    args = parser.parse_args()
    try:
        data = INVENTORY.read_bytes()
        inventory = json.loads(data)
        validate(inventory)
        output = render(inventory, hashlib.sha256(data).hexdigest())
        if args.check:
            if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != output:
                print("adoption-docs: stale projection; run python3 scripts/render-adoption-docs.py", file=sys.stderr)
                return 1
            print(f"adoption-docs: ok ({len(inventory['integrations'])} inventory entries)")
        else:
            OUTPUT.parent.mkdir(parents=True, exist_ok=True)
            OUTPUT.write_text(output, encoding="utf-8")
            print(f"adoption-docs: wrote {OUTPUT.relative_to(ROOT)}")
        return 0
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print(f"adoption-docs: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
