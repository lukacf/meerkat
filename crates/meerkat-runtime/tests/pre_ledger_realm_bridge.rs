/// The honest-remedy predicate, evaluated against real released bytes, and
/// evaluated against the realm that actually has rows in it.
///
/// THIS IS THE ANTI-REGRESSION FOR THE FALSE PROMISE. Round one pinned this
/// test to `bootstrap-only` precisely because `attempted-turn` would have
/// exposed the divergence: the predicate said "recoverable" over a file the
/// bridge then refused eighty lines below. A predicate that answers about
/// catalog shape is fine; a predicate whose answer is rendered to an operator
/// as "run the bridge and retry" while the bridge refuses that same file is
/// the defect. So the subject here is every row-bearing capture, and the
/// assertion is agreement between the two oracles: whatever the predicate
/// promises, the bridge must deliver on the identical bytes.
#[test]
fn bridge_eligibility_agrees_with_the_bridge_on_row_bearing_realms() {
    let manifest = load_manifest();
    let row_bearing = captures(&manifest)
        .into_iter()
        .filter(|(_, capture)| capture.carries_runtime_input_rows)
        .collect::<Vec<_>>();
    assert!(
        !row_bearing.is_empty(),
        "this test is meaningless without a row-bearing capture"
    );

    // EVERY domain in the file, not just the runtime store. The predecessor of
    // this test asked only the runtime domain, which had always answered
    // correctly, so it stayed green while an ordinary open told operators that
    // the *session* domain of the very same realm was unrecoverable. A test
    // that samples one of three co-tenants is not an oracle for the sentence
    // the product prints.
    let sessions_file_domains: [&meerkat_sqlite::SchemaDomain; 3] = [
        &meerkat_store::sqlite_store::SESSION_STORE_DOMAIN,
        &meerkat_runtime::store::sqlite::RUNTIME_STORE_DOMAIN,
        &meerkat_store::schedule_sqlite_store::SCHEDULE_STORE_DOMAIN,
    ];
    for (release, capture) in row_bearing {
        let label = format!("{}/{}", release.meerkat_version, capture.capture_id);
        let source = capture_root(capture).join("sessions.sqlite3");
        let scratch = tempfile::tempdir().expect("tempdir");
        let database = scratch.path().join("sessions.sqlite3");
        std::fs::copy(&source, &database).expect("copy corpus");

        for domain in sessions_file_domains {
            let promised = {
                let conn =
                    meerkat_sqlite::open(&database, meerkat_sqlite::ConnectionProfile::ReadOnly)
                        .expect("open corpus read-only");
                assert_eq!(
                    domain.bridgeable_source_version(&conn),
                    Some(1),
                    "{label}: the 0.7.x {} catalog authenticates as version 1",
                    domain.name
                );
                domain.bridge_eligibility(&conn)
            };
            assert_eq!(
                promised,
                meerkat_sqlite::BridgeEligibility::CatalogAuthenticated,
                "{label}: a realm written by published rkat must be reported as bridgeable, \
                 including its {} domain",
                domain.name
            );
        }

        // The same bytes, through the oracle the operator's command actually
        // runs. `CatalogAuthenticated` must mean the domain lands.
        let delivered = bridge_one_capture(&label, &capture_root(capture));
        assert!(
            delivered.is_ok(),
            "{label}: eligibility promised every domain was bridgeable and the bridge then \
             refused the same file. That is the false promise this P0 exists to remove.\n{}",
            delivered.unwrap_err()
        );
    }
}

