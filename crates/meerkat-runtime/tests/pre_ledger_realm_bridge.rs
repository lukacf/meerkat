            let mut conn = meerkat_sqlite::open(
                &database,
                meerkat_sqlite::ConnectionProfile::Maintenance { write: true },
            )
            .expect("open corpus for maintenance");
            let tx = conn.transaction().expect("tx");
            let report =
                meerkat_runtime::store::sqlite::prepare_pre_0_8_10_runtime_input_states(&tx)
                    .unwrap_or_else(|error| panic!("{label}: callback refused the realm: {error}"));
            assert_eq!(
                report.changed,
                before.len(),
                "{label}: the callback must carry every row it was given"
            );
            assert!(
                report.refused.is_empty(),
                "{label}: the callback left records behind: {:?}",
                report.refused
            );
